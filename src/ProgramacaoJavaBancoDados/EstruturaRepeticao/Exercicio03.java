// Exercício 3 — Tabuada.
public class Exercicio03 {
    public static void main(String[] args) {
        int numero = 5;
        for (int i = 1; i <= 10; i++) {
            System.out.println(numero + " x " + i + " = " + (numero * i));
        }
    }
}
